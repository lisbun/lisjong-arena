"""Tenpai PUSH/FOLD paired source producer and pilot (lisjong-arena#476).

Writes the lisbun/lisjong#288 wire contract (lisjong
``docs/tenpai-push-fold-source.md``): for every gate decision of a Champion
self-play hanchan on lisjong-engine, the decider's round result when it pushes
(the control) and, when a fold candidate exists, when it discards ``a_fold``
at that decision only.

- Control: Champion x4.  Every selector call's Champion ``PolicyDecision`` goes
  to lisjong's ``evaluate_tenpai_gate()``; a non-``None`` result is a gate
  decision.  Arena implements no gate condition and picks no candidate.
- Fold side: per gate decision with ``has_fold_candidate``, the same seed is
  played again from the start with the decider's seat replaced by lisjong's
  ``TenpaiPushFoldPairPolicy``, and stopped when that round is settled.  Arena
  never substitutes an action itself.
- Determinism: every selector call of a fold-side run up to the target must be
  the control's (same ``DecisionContext``, same action), and the target call
  must return ``a_fold``.  A difference, or a target that never appears, stops
  the generation; nothing is written.
- Round results are the engine's ``RoundCompletionFact`` (point deltas,
  winners, settlement transfers, tenpai seats).  Arena computes no score.
- ``decisions.jsonl`` holds only the decider's ``PolicyInput`` and legal
  actions; no file holds another seat's hand or the wall.

Output directory (new; an existing path is refused)::

    manifest.json     lisjong-tenpai-push-fold-source-manifest-v1
    decisions.jsonl   lisjong-tenpai-push-fold-decision-record-v1
    outcomes.jsonl    lisjong-tenpai-push-fold-outcome-record-v1
    generation.json   Arena evidence (counts, timing, runtime; not read by lisjong)

The three wire files depend only on the seeds, the split and the producer
revisions, so the same input regenerates them byte for byte.

``run`` is the pilot: its seeds (938000..938015), split and allocation are
fixed and no argument changes them.  ``development`` replays already RETIRED
lisjong-arena#385 seeds (931000..931999) to check the path; its output is not
a pilot result.  The production population is registered after the pilot and
is not generated by this script.

Usage::

    LISJONG_SHANTEN_BACKEND=rust python scripts/generate_tenpai_push_fold_source_476.py \\
        run --seed-ledger <live ledger> --allocation-identity <sha256> \\
        --selection <selection.json> --workers 8 --output <new directory>
    LISJONG_SHANTEN_BACKEND=rust python scripts/generate_tenpai_push_fold_source_476.py \\
        development --train 931400..931400 --valid 931401..931401 \\
        --selection <selection.json> --workers 2 --output <new directory>
    python scripts/generate_tenpai_push_fold_source_476.py check-allocation \\
        --seed-ledger <live ledger> --allocation-identity <sha256> \\
        --arena-revision <full sha>

Generated data is not committed.
"""

