"""Stage 4a Gate 0: candidate generation -> retention -> strict readback。

```text
locked generation population (TRAIN 200..209 / VALIDATION 210..212)
    -> Stage 2 locked model / training config
    -> Stage 4a candidate bundle (operator-declared non-ephemeral root配下)
        <retention root>/<retention key>/
            checkpoint/            exact retained weights + manifest
            candidate-freeze.json  Stage 4a-owned freeze record
    -> strict loader readback
    -> freeze record binding (identity / digest / bytes / schema)
```

**checkpoint format reuse**: on-diskのcheckpoint directory formatと、その
strict loaderはStage 3が確立したimplementation primitiveをそのまま使う
(`lisbun/lisjong-arena #138`が明示的に許すminimal path)。Stage 4a固有の
freeze identity / purposeはこのmoduleが所有する`candidate-freeze.json`が
持ち、checkpoint側のschemaを再設計しない。

したがって次を混同しない。

- **historical Stage 3 fixture**: serving integration専用のhistorical artifact。
  Stage 4aはこれをstrength evidenceへaliasしない
- **Stage 4a candidate**: このmoduleがGate 0で新規生成し、freeze recordで
  purposeとidentityを宣言し、non-ephemeral locationへretainしたbundle

candidate identityは`learned-stage4a:<checkpoint identity>`であり、strict
loadしたcheckpoint identityから機械的に導出する。free-form aliasを与える
入口を持たない。

**durability boundary**: 実際のstorage durabilityはcaller / operatorの宣言で
ある。このmoduleが機械的にfail closedできるのは「temporary directoryでない」
「Git work tree内でない」「既存destinationを上書きしない」までであり、
declared backendはfreeze recordへそのまま記録して監査可能にする。宣言できる
non-ephemeral rootが無い場合、callerは`Stage4aRetentionError`のまま
`ARTIFACT RETENTION BLOCKED`として停止する。
"""

